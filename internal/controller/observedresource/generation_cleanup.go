const (
	policyLabel      = "admitik.dev/policy"
	parentAnnotation = "admitik.dev/parent"
)

// parentReference identifies the object that triggered a generation as kind/namespace/name
func parentReference(object map[string]any) string {
	metadata, _ := object["metadata"].(map[string]any)
	kind, _ := object["kind"].(string)
	namespace, _ := metadata["namespace"].(string)
	name, _ := metadata["name"].(string)

	return fmt.Sprintf("%s/%s/%s", kind, namespace, name)
}

// markGenerated stamps a generated object with the policy and parent that own it
func markGenerated(obj *unstructured.Unstructured, policyName, parent string) {
	labels := obj.GetLabels()
	if labels == nil {
		labels = map[string]string{}
	}
	labels[policyLabel] = policyName
	obj.SetLabels(labels)

	annotations := obj.GetAnnotations()
	if annotations == nil {
		annotations = map[string]string{}
	}
	annotations[parentAnnotation] = parent
	obj.SetAnnotations(annotations)
}

// isGeneratedBy tells whether an object was generated by the given policy for the given parent
func isGeneratedBy(obj *unstructured.Unstructured, policyName, parent string) bool {
	return obj.GetLabels()[policyLabel] == policyName && obj.GetAnnotations()[parentAnnotation] == parent
}

// shouldCleanup decides whether previously generated resources must be removed after an event
func shouldCleanup(enabled bool, operation string, oldPassed, newPassed bool) bool {
	if !enabled {
		return false
	}

	switch operation {
	case common.NormalizedOperationUpdate:
		return oldPassed && !newPassed
	case common.NormalizedOperationDelete:
		return oldPassed
	}

	return false
}

// previousStateData builds the evaluation data as it was before the event, so templates
// render the same object that was generated back then
func previousStateData(data *template.PolicyEvaluationDataT, previous map[string]any) template.PolicyEvaluationDataT {
	previousData := *data
	previousData.Object = previous
	previousData.OldObject = map[string]any{}

	return previousData
}

// renderGeneratedObject evaluates the policy's object template and decodes the result
func renderGeneratedObject(policy *v1alpha1.ClusterGenerationPolicy, data *template.PolicyEvaluationDataT) (map[string]any, error) {
	parsed, err := template.EvaluateTemplate(policy.Spec.Object.Definition.Engine,
		policy.Spec.Object.Definition.Template, data)
	if err != nil {
		return nil, err
	}

	var rendered map[string]any
	if err = yaml.Unmarshal([]byte(parsed), &rendered); err != nil {
		return nil, err
	}

	return rendered, nil
}

// deleteGeneratedObject renders the policy template with the previous state of the parent and
// deletes the resulting object, only when it carries the ownership marks of that policy and parent
func (p *GenerationProcessor) deleteGeneratedObject(policy *v1alpha1.ClusterGenerationPolicy,
	data *template.PolicyEvaluationDataT, parent string) (err error) {

	logger := log.FromContext(globals.Application.Context).WithValues("ClusterGenerationPolicy", policy.Name, "parent", parent)

	rendered, err := renderGeneratedObject(policy, data)
	if err != nil {
		return fmt.Errorf("rendering object to delete: %w", err)
	}

	basicData, err := globals.GetObjectBasicData(&rendered)
	if err != nil {
		return fmt.Errorf("obtaining metadata of object to delete: %w", err)
	}

	resource := getResourceFromGvk(p.dependencies.KubeAvailableResourceList, schema.GroupVersionKind{
		Group:   basicData.Group,
		Version: basicData.Version,
		Kind:    basicData.Kind,
	})
	if resource == "" {
		return fmt.Errorf("unknown resource for GVK %s/%s %s", basicData.Group, basicData.Version, basicData.Kind)
	}

	resourceClient := globals.Application.KubeRawClient.
		Resource(schema.GroupVersionResource{Group: basicData.Group, Version: basicData.Version, Resource: resource}).
		Namespace(basicData.Namespace)

	current, err := resourceClient.Get(globals.Application.Context, basicData.Name, metav1.GetOptions{})
	if err != nil {
		if errors.IsNotFound(err) {
			return nil
		}
		return fmt.Errorf("getting object to delete: %w", err)
	}

	if !isGeneratedBy(current, policy.Name, parent) {
		logger.Info("skipping deletion: object is not owned by this policy and parent",
			"resource", resource, "name", basicData.Name, "namespace", basicData.Namespace)
		return nil
	}

	uid := current.GetUID()
	err = resourceClient.Delete(globals.Application.Context, basicData.Name, metav1.DeleteOptions{
		Preconditions: &metav1.Preconditions{UID: &uid},
	})
	if err != nil && !errors.IsNotFound(err) {
		return fmt.Errorf("deleting object: %w", err)
	}

	logger.Info("deleted generated object", "resource", resource, "name", basicData.Name, "namespace", basicData.Namespace)
	return nil
}
