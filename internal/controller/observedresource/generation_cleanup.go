const (
	policyLabel           = "admitik.dev/policy"
	triggerUIDLabel       = "admitik.dev/trigger-uid"
	triggerGroupLabel     = "admitik.dev/trigger-group"
	triggerVersionLabel   = "admitik.dev/trigger-version"
	triggerKindLabel      = "admitik.dev/trigger-kind"
	triggerNamespaceLabel = "admitik.dev/trigger-namespace"

	eventActionGeneratedObjectDeleted        = "GeneratedObjectDeleted"
	eventActionGeneratedObjectDeletionFailed = "GeneratedObjectDeletionFailed"
)

var ownershipLabels = []string{
	policyLabel, triggerUIDLabel, triggerGroupLabel, triggerVersionLabel, triggerKindLabel, triggerNamespaceLabel,
}

// triggerRef identifies the watched object that triggered a generation
type triggerRef struct {
	UID       string
	Group     string
	Version   string
	Kind      string
	Namespace string
}

func triggerFromObject(object map[string]any) triggerRef {
	metadata, _ := object["metadata"].(map[string]any)
	apiVersion, _ := object["apiVersion"].(string)
	kind, _ := object["kind"].(string)
	namespace, _ := metadata["namespace"].(string)
	uid, _ := metadata["uid"].(string)

	group, version := "", apiVersion
	if before, after, found := strings.Cut(apiVersion, "/"); found {
		group, version = before, after
	}

	return triggerRef{UID: uid, Group: group, Version: version, Kind: kind, Namespace: namespace}
}

// markGenerated stamps a generated object with the policy and trigger that own it
func markGenerated(obj *unstructured.Unstructured, policyName string, trigger triggerRef) {
	labels := obj.GetLabels()
	if labels == nil {
		labels = map[string]string{}
	}

	labels[policyLabel] = policyName
	labels[triggerUIDLabel] = trigger.UID
	labels[triggerGroupLabel] = trigger.Group
	labels[triggerVersionLabel] = trigger.Version
	labels[triggerKindLabel] = trigger.Kind
	labels[triggerNamespaceLabel] = trigger.Namespace
	obj.SetLabels(labels)
}

// unmarkGenerated removes ownership labels so admitik never claims an object it did not create
func unmarkGenerated(obj *unstructured.Unstructured) {
	labels := obj.GetLabels()
	for _, label := range ownershipLabels {
		delete(labels, label)
	}
	obj.SetLabels(labels)
}

// isGeneratedBy tells whether an object was generated by the given policy for the given trigger
func isGeneratedBy(obj *unstructured.Unstructured, policyName, triggerUID string) bool {
	labels := obj.GetLabels()
	return triggerUID != "" && labels[policyLabel] == policyName && labels[triggerUIDLabel] == triggerUID
}

// shouldCleanup decides whether previously generated objects must be removed after an event.
// Any evaluation error blocks the cleanup: a failure is not proof that conditions stopped matching
func shouldCleanup(enabled bool, operation string, oldPassed, newPassed, evaluationFailed bool) bool {
	if !enabled || evaluationFailed {
		return false
	}

	switch operation {
	case common.NormalizedOperationUpdate:
		return oldPassed && !newPassed
	case common.NormalizedOperationDelete:
		return oldPassed
	}

	return false
}

// previousStateData builds the evaluation data as it was before the event, so templates
// render the same object that was generated back then
func previousStateData(data *template.PolicyEvaluationDataT, previous map[string]any) template.PolicyEvaluationDataT {
	previousData := *data
	previousData.Object = previous
	previousData.OldObject = map[string]any{}

	return previousData
}

// renderGeneratedObject evaluates the policy's object template and decodes the result
func renderGeneratedObject(policy *v1alpha1.ClusterGenerationPolicy, data *template.PolicyEvaluationDataT) (map[string]any, error) {
	parsed, err := template.EvaluateTemplate(policy.Spec.Object.Definition.Engine,
		policy.Spec.Object.Definition.Template, data)
	if err != nil {
		return nil, err
	}

	var rendered map[string]any
	if err = yaml.Unmarshal([]byte(parsed), &rendered); err != nil {
		return nil, err
	}

	return rendered, nil
}

// cleanupGenerated deletes the object generated for a trigger that stopped meeting the conditions
// or was deleted. It never deletes when anything about the decision is uncertain
func (p *GenerationProcessor) cleanupGenerated(policy *v1alpha1.ClusterGenerationPolicy, object []map[string]any,
	data *template.PolicyEvaluationDataT, newPassed, evaluationFailed bool) {

	logger := log.FromContext(globals.Application.Context).WithValues("ClusterGenerationPolicy", policy.Name)

	previousData := *data
	oldPassed := newPassed
	if data.Operation == common.NormalizedOperationUpdate {
		var oldErr error
		previousData = previousStateData(data, object[1])
		oldPassed, oldErr = common.IsPassingConditions(policy.Spec.Conditions, &previousData)
		evaluationFailed = evaluationFailed || oldErr != nil
	}

	if !shouldCleanup(true, data.Operation, oldPassed, newPassed, evaluationFailed) {
		if evaluationFailed {
			logger.Info("skipping cleanup of generated objects: sources or conditions failed to evaluate")
		}
		return
	}

	trigger := triggerFromObject(previousData.Object)
	deleted, err := p.deleteGeneratedObject(policy, &previousData, trigger.UID)

	action, message := "", ""
	switch {
	case err != nil:
		logger.Info(fmt.Sprintf("failed deleting generated object: %s", err.Error()))
		action, message = eventActionGeneratedObjectDeletionFailed, "Generated object deletion failed. More info in controller logs."
	case deleted:
		action, message = eventActionGeneratedObjectDeleted, "Generated object deleted as conditions are no longer met."
	default:
		return
	}

	if err = common.CreateKubeEvent(globals.Application.Context, "default", "resources-controller",
		object[0], *policy, action, message); err != nil {
		logger.Info(fmt.Sprintf("failed creating Kubernetes event: %s", err.Error()))
	}
}

// deleteGeneratedObject renders the policy template with the previous state of the trigger and
// deletes the resulting object, only when it carries the ownership labels of that policy and trigger
func (p *GenerationProcessor) deleteGeneratedObject(policy *v1alpha1.ClusterGenerationPolicy,
	data *template.PolicyEvaluationDataT, triggerUID string) (deleted bool, err error) {

	logger := log.FromContext(globals.Application.Context).WithValues("ClusterGenerationPolicy", policy.Name, "triggerUID", triggerUID)

	rendered, err := renderGeneratedObject(policy, data)
	if err != nil {
		return false, fmt.Errorf("rendering object to delete: %w", err)
	}

	basicData, err := globals.GetObjectBasicData(&rendered)
	if err != nil {
		return false, fmt.Errorf("obtaining metadata of object to delete: %w", err)
	}

	resource := getResourceFromGvk(p.dependencies.KubeAvailableResourceList, schema.GroupVersionKind{
		Group:   basicData.Group,
		Version: basicData.Version,
		Kind:    basicData.Kind,
	})
	if resource == "" {
		return false, fmt.Errorf("unknown resource for GVK %s/%s %s", basicData.Group, basicData.Version, basicData.Kind)
	}

	resourceClient := globals.Application.KubeRawClient.
		Resource(schema.GroupVersionResource{Group: basicData.Group, Version: basicData.Version, Resource: resource}).
		Namespace(basicData.Namespace)
	logger = logger.WithValues("resource", resource, "name", basicData.Name, "namespace", basicData.Namespace)

	deleted, err = deleteIfOwned(globals.Application.Context, resourceClient, basicData.Name, policy.Name, triggerUID)
	if err == nil && !deleted {
		logger.Info("skipping deletion: object not found or not owned by this policy and trigger")
	}
	if deleted {
		logger.Info("deleted generated object")
	}
	return deleted, err
}

// deleteIfOwned deletes an object only when it carries the ownership labels of the policy and trigger.
// UID and resourceVersion preconditions guarantee the deleted object is exactly the one that was checked
func deleteIfOwned(ctx context.Context, resourceClient dynamic.ResourceInterface, name, policyName, triggerUID string) (bool, error) {
	current, err := resourceClient.Get(ctx, name, metav1.GetOptions{})
	if err != nil {
		if errors.IsNotFound(err) {
			return false, nil
		}
		return false, fmt.Errorf("getting object to delete: %w", err)
	}

	if !isGeneratedBy(current, policyName, triggerUID) {
		return false, nil
	}

	uid := current.GetUID()
	resourceVersion := current.GetResourceVersion()
	err = resourceClient.Delete(ctx, name, metav1.DeleteOptions{
		Preconditions: &metav1.Preconditions{UID: &uid, ResourceVersion: &resourceVersion},
	})
	if err != nil {
		if errors.IsNotFound(err) {
			return false, nil
		}
		return false, fmt.Errorf("deleting object: %w", err)
	}

	return true, nil
}

// keepMarksOnlyIfOwned strips ownership labels before overwriting an object admitik did not create,
// so pre-existing objects are never adopted and therefore never deleted
func keepMarksOnlyIfOwned(ctx context.Context, resourceClient dynamic.ResourceInterface, obj *unstructured.Unstructured,
	policyName, triggerUID string) {

	current, err := resourceClient.Get(ctx, obj.GetName(), metav1.GetOptions{})
	if err != nil || !isGeneratedBy(current, policyName, triggerUID) {
		unmarkGenerated(obj)
	}
}
