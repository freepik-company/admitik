var configMapsGVR = schema.GroupVersionResource{Version: "v1", Resource: "configmaps"}

func configMap(name string, labels map[string]string) *unstructured.Unstructured {
	obj := &unstructured.Unstructured{}
	obj.SetAPIVersion("v1")
	obj.SetKind("ConfigMap")
	obj.SetNamespace("team-a")
	obj.SetName(name)
	obj.SetUID(types.UID("cm-" + name))
	obj.SetLabels(labels)
	return obj
}

func ownedConfigMap(name, policy, triggerUID string) *unstructured.Unstructured {
	obj := configMap(name, map[string]string{"managed-by": "admitik"})
	markGenerated(obj, policy, triggerRef{UID: triggerUID, Kind: "Deployment", Namespace: "team-a"})
	return obj
}

func configMapsClient(objects ...runtime.Object) dynamic.ResourceInterface {
	client := dynamicfake.NewSimpleDynamicClientWithCustomListKinds(runtime.NewScheme(),
		map[schema.GroupVersionResource]string{configMapsGVR: "ConfigMapList"}, objects...)
	return client.Resource(configMapsGVR).Namespace("team-a")
}

func TestDeleteIfOwned(t *testing.T) {
	tests := []struct {
		name        string
		existing    *unstructured.Unstructured
		wantDeleted bool
	}{
		{"owned by policy and trigger", ownedConfigMap("exporter", "demo-policy", "uid-1"), true},
		{"generated for another trigger", ownedConfigMap("exporter", "demo-policy", "uid-2"), false},
		{"generated by another policy", ownedConfigMap("exporter", "other", "uid-1"), false},
		{"pre-existing object without marks", configMap("exporter", map[string]string{"managed-by": "admitik"}), false},
		{"object does not exist", nil, false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			objects := []runtime.Object{}
			if tt.existing != nil {
				objects = append(objects, tt.existing)
			}
			client := configMapsClient(objects...)

			deleted, err := deleteIfOwned(context.Background(), client, "exporter", "demo-policy", "uid-1")
			if err != nil {
				t.Fatalf("deleteIfOwned() unexpected error: %v", err)
			}
			if deleted != tt.wantDeleted {
				t.Fatalf("deleteIfOwned() deleted = %v, want %v", deleted, tt.wantDeleted)
			}

			_, getErr := client.Get(context.Background(), "exporter", metav1.GetOptions{})
			stillExists := getErr == nil
			if tt.existing != nil && stillExists == tt.wantDeleted {
				t.Fatalf("object existence after call = %v, want deleted = %v", stillExists, tt.wantDeleted)
			}
			if getErr != nil && !errors.IsNotFound(getErr) {
				t.Fatalf("unexpected get error: %v", getErr)
			}
		})
	}
}

func TestKeepMarksOnlyIfOwned(t *testing.T) {
	tests := []struct {
		name      string
		existing  *unstructured.Unstructured
		wantMarks bool
	}{
		{"keeps marks on own object", ownedConfigMap("exporter", "demo-policy", "uid-1"), true},
		{"strips marks on object of another trigger", ownedConfigMap("exporter", "demo-policy", "uid-2"), false},
		{"strips marks on pre-existing object", configMap("exporter", nil), false},
		{"strips marks when object cannot be read", nil, false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			objects := []runtime.Object{}
			if tt.existing != nil {
				objects = append(objects, tt.existing)
			}
			client := configMapsClient(objects...)
			desired := ownedConfigMap("exporter", "demo-policy", "uid-1")

			keepMarksOnlyIfOwned(context.Background(), client, desired, "demo-policy", "uid-1")

			if got := isGeneratedBy(desired, "demo-policy", "uid-1"); got != tt.wantMarks {
				t.Fatalf("desired object keeps marks = %v, want %v", got, tt.wantMarks)
			}
			if desired.GetLabels()["managed-by"] != "admitik" {
				t.Fatalf("template labels must be preserved, got %v", desired.GetLabels())
			}
		})
	}
}
