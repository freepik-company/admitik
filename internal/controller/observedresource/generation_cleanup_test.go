package observedresource

import (
	"testing"

	"k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"

	"github.com/freepik-company/admitik/internal/common"
)

func parentObject(kind, namespace, name string) map[string]any {
	return map[string]any{
		"kind": kind,
		"metadata": map[string]any{
			"namespace": namespace,
			"name":      name,
		},
	}
}

func TestParentReference(t *testing.T) {
	got := parentReference(parentObject("Deployment", "microservices", "api"))
	want := "Deployment/microservices/api"
	if got != want {
		t.Fatalf("parentReference() = %q, want %q", got, want)
	}
}

func TestMarkGeneratedSetsOwnershipAndKeepsExistingMetadata(t *testing.T) {
	obj := &unstructured.Unstructured{Object: map[string]any{
		"metadata": map[string]any{
			"labels":      map[string]any{"managed-by": "admitik"},
			"annotations": map[string]any{"keep": "me"},
		},
	}}

	markGenerated(obj, "redis-policy", "Deployment/microservices/api")

	if obj.GetLabels()[policyLabel] != "redis-policy" || obj.GetLabels()["managed-by"] != "admitik" {
		t.Fatalf("unexpected labels: %v", obj.GetLabels())
	}
	if obj.GetAnnotations()[parentAnnotation] != "Deployment/microservices/api" || obj.GetAnnotations()["keep"] != "me" {
		t.Fatalf("unexpected annotations: %v", obj.GetAnnotations())
	}
}

func TestIsGeneratedBy(t *testing.T) {
	build := func(policy, parent string) *unstructured.Unstructured {
		obj := &unstructured.Unstructured{Object: map[string]any{"metadata": map[string]any{}}}
		if policy != "" {
			markGenerated(obj, policy, parent)
		}
		return obj
	}

	tests := []struct {
		name   string
		obj    *unstructured.Unstructured
		policy string
		parent string
		want   bool
	}{
		{"same policy and parent", build("p", "Deployment/ns/a"), "p", "Deployment/ns/a", true},
		{"other parent using same policy", build("p", "Deployment/other/b"), "p", "Deployment/ns/a", false},
		{"other policy", build("q", "Deployment/ns/a"), "p", "Deployment/ns/a", false},
		{"object not generated by admitik", build("", ""), "p", "Deployment/ns/a", false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := isGeneratedBy(tt.obj, tt.policy, tt.parent); got != tt.want {
				t.Fatalf("isGeneratedBy() = %v, want %v", got, tt.want)
			}
		})
	}
}

func TestShouldCleanup(t *testing.T) {
	tests := []struct {
		name      string
		enabled   bool
		operation string
		oldPassed bool
		newPassed bool
		want      bool
	}{
		{"disabled never cleans", false, common.NormalizedOperationUpdate, true, false, false},
		{"update that stops matching", true, common.NormalizedOperationUpdate, true, false, true},
		{"update that keeps matching", true, common.NormalizedOperationUpdate, true, true, false},
		{"update that never matched", true, common.NormalizedOperationUpdate, false, false, false},
		{"update that starts matching", true, common.NormalizedOperationUpdate, false, true, false},
		{"parent deleted while matching", true, common.NormalizedOperationDelete, true, true, true},
		{"parent deleted that never matched", true, common.NormalizedOperationDelete, false, false, false},
		{"create never cleans", true, common.NormalizedOperationCreate, false, true, false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := shouldCleanup(tt.enabled, tt.operation, tt.oldPassed, tt.newPassed)
			if got != tt.want {
				t.Fatalf("shouldCleanup() = %v, want %v", got, tt.want)
			}
		})
	}
}
