package observedresource

import (
	"testing"

	"k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"

	"github.com/freepik-company/admitik/internal/common"
)

func triggerObject(apiVersion, kind, namespace, name, uid string) map[string]any {
	return map[string]any{
		"apiVersion": apiVersion,
		"kind":       kind,
		"metadata": map[string]any{
			"namespace": namespace,
			"name":      name,
			"uid":       uid,
		},
	}
}

func emptyObject() *unstructured.Unstructured {
	return &unstructured.Unstructured{Object: map[string]any{"metadata": map[string]any{}}}
}

func TestTriggerFromObject(t *testing.T) {
	tests := []struct {
		name   string
		object map[string]any
		want   triggerRef
	}{
		{
			"grouped resource",
			triggerObject("apps/v1", "Deployment", "microservices", "api", "uid-1"),
			triggerRef{UID: "uid-1", Group: "apps", Version: "v1", Kind: "Deployment", Namespace: "microservices"},
		},
		{
			"core resource",
			triggerObject("v1", "Service", "pikaso", "web", "uid-2"),
			triggerRef{UID: "uid-2", Group: "", Version: "v1", Kind: "Service", Namespace: "pikaso"},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := triggerFromObject(tt.object); got != tt.want {
				t.Fatalf("triggerFromObject() = %+v, want %+v", got, tt.want)
			}
		})
	}
}

func TestMarkGeneratedSetsOwnershipLabelsAndKeepsExistingOnes(t *testing.T) {
	obj := &unstructured.Unstructured{Object: map[string]any{
		"metadata": map[string]any{"labels": map[string]any{"managed-by": "admitik"}},
	}}
	trigger := triggerRef{UID: "uid-1", Group: "apps", Version: "v1", Kind: "Deployment", Namespace: "microservices"}

	markGenerated(obj, "redis-policy", trigger)

	want := map[string]string{
		"managed-by":          "admitik",
		policyLabel:           "redis-policy",
		triggerUIDLabel:       "uid-1",
		triggerGroupLabel:     "apps",
		triggerVersionLabel:   "v1",
		triggerKindLabel:      "Deployment",
		triggerNamespaceLabel: "microservices",
	}
	got := obj.GetLabels()
	for key, value := range want {
		if got[key] != value {
			t.Fatalf("label %q = %q, want %q (labels: %v)", key, got[key], value, got)
		}
	}
}

func TestUnmarkGeneratedRemovesOnlyOwnershipLabels(t *testing.T) {
	obj := emptyObject()
	obj.SetLabels(map[string]string{"managed-by": "admitik"})
	markGenerated(obj, "redis-policy", triggerRef{UID: "uid-1", Kind: "Deployment"})

	unmarkGenerated(obj)

	labels := obj.GetLabels()
	if len(labels) != 1 || labels["managed-by"] != "admitik" {
		t.Fatalf("unexpected labels after unmark: %v", labels)
	}
}

func TestIsGeneratedBy(t *testing.T) {
	build := func(policy, uid string) *unstructured.Unstructured {
		obj := emptyObject()
		if policy != "" {
			markGenerated(obj, policy, triggerRef{UID: uid, Kind: "Deployment"})
		}
		return obj
	}

	tests := []struct {
		name       string
		obj        *unstructured.Unstructured
		policy     string
		triggerUID string
		want       bool
	}{
		{"same policy and trigger", build("p", "uid-1"), "p", "uid-1", true},
		{"other trigger using same policy", build("p", "uid-2"), "p", "uid-1", false},
		{"recreated trigger with same name", build("p", "old-uid"), "p", "new-uid", false},
		{"other policy", build("q", "uid-1"), "p", "uid-1", false},
		{"object not generated by admitik", build("", ""), "p", "uid-1", false},
		{"empty trigger uid never matches", build("p", ""), "p", "", false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := isGeneratedBy(tt.obj, tt.policy, tt.triggerUID); got != tt.want {
				t.Fatalf("isGeneratedBy() = %v, want %v", got, tt.want)
			}
		})
	}
}

func TestShouldCleanup(t *testing.T) {
	tests := []struct {
		name             string
		enabled          bool
		operation        string
		oldPassed        bool
		newPassed        bool
		evaluationFailed bool
		want             bool
	}{
		{"disabled never cleans", false, common.NormalizedOperationUpdate, true, false, false, false},
		{"update that stops matching", true, common.NormalizedOperationUpdate, true, false, false, true},
		{"update that keeps matching", true, common.NormalizedOperationUpdate, true, true, false, false},
		{"update that never matched", true, common.NormalizedOperationUpdate, false, false, false, false},
		{"update that starts matching", true, common.NormalizedOperationUpdate, false, true, false, false},
		{"update with evaluation error", true, common.NormalizedOperationUpdate, true, false, true, false},
		{"trigger deleted while matching", true, common.NormalizedOperationDelete, true, true, false, true},
		{"trigger deleted that never matched", true, common.NormalizedOperationDelete, false, false, false, false},
		{"trigger deleted with evaluation error", true, common.NormalizedOperationDelete, true, true, true, false},
		{"create never cleans", true, common.NormalizedOperationCreate, false, true, false, false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := shouldCleanup(tt.enabled, tt.operation, tt.oldPassed, tt.newPassed, tt.evaluationFailed)
			if got != tt.want {
				t.Fatalf("shouldCleanup() = %v, want %v", got, tt.want)
			}
		})
	}
}
